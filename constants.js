// Normaliza un nombre de imagen para comparar (sin extensión, separadores ni mayúsculas)
const normalizeImgKey = (name) => String(name || '')
    .normalize('NFC')
    .replace(/\.[^.]+$/, '')
    .replace(/[\s_\-]/g, '')
    .toLowerCase();

let _imgIndex = null;

// Devuelve la ruta de la imagen; si el producto tiene un nombre antiguo (ej: Agua_Loa_3L.svg)
// busca la versión renombrada (ej: AGUA-LOA-3L.svg). Si no existe, usa el logo.
export function resolveImage(imagen) {
    if (!imagen) return './kalo-logo.png';
    if (!_imgIndex) {
        _imgIndex = new Map();
        AVAILABLE_IMAGES.forEach(f => _imgIndex.set(normalizeImgKey(f), f));
    }
    const exact = AVAILABLE_IMAGES.includes(imagen) ? imagen : _imgIndex.get(normalizeImgKey(imagen));
    return exact ? `./img/${encodeURI(exact)}` : './kalo-logo.png';
}

